func sprintf(format string, args ...any) string { return fmt.Sprintf(format, args...) }

// kind of the Rust expression a translation produced.
type kind int

const (
	kOwned    kind = iota // a fresh owned value of rtype(T)
	kPlace                // a place of type rtype(T) (variable, field): `.clone()` to own it
	kStr                  // &str
	kSlice                // &[elemType(T)]
	kStrSlice             // &[&str]
	kRef                  // &rtype(T) (closure parameters of iterator helpers)
	kOptArc               // Option<Arc<T>>: a harness-object pointer stored in a struct field
	kDeref                // the pointee T of a Go *T that Rust stores unboxed (element of a []*T): never nil
)

type varInfo struct {
	name string
	kind kind
	// fclosure: a func value produced by the harness (DoneFn & co): called with (f, t) prepended.
	fclosure bool
	// takesF: a local closure that receives the FourslashTest as its first argument.
	takesF bool
	fOwner string // for fclosures: the FourslashTest variable they belong to
	// constant string/number bound with `let` (no clone needed).
}

type gen struct {
	l    *Loaded
	p    *Package
	info *types.Info
	fset *token.FileSet

	vars map[types.Object]*varInfo
	used map[types.Object]bool
	curF string // Rust name of the innermost FourslashTest variable ("" if none)
	curT string // Rust name of the innermost *testing.T variable
	// names of package-level declarations of the current file (Rust names).
	tmp int

	buf    *strings.Builder
	indent int

	// statistics
	untranslatedCounts map[string]int
	anyVariants        map[string]int
	localTypes         map[*types.TypeName]string
	assigned           map[types.Object]bool
	resultTypes        []types.Type
	inResultFunc       bool
}

func (g *gen) line(format string, args ...any) {
	g.buf.WriteString(strings.Repeat("    ", g.indent))
	fmt.Fprintf(g.buf, format, args...)
	g.buf.WriteByte('\n')
}

func (g *gen) pos(n ast.Node) token.Position { return g.fset.Position(n.Pos()) }

func (g *gen) newTmp(prefix string) string {
	g.tmp++
	return fmt.Sprintf("__%s%d", prefix, g.tmp)
}

type testEntry struct {
	goName  string
	file    string
	module  string
	fn      string
	skip    string
	skipped bool
	line    int
}

type fileOut struct {
	module string
	code   string
	tests  []testEntry
}

var modRefRe = regexp.MustCompile(`@@MOD:([a-z0-9_]+)@@`)

func generate(l *Loaded, out string, perFile int) error {
	if perFile <= 0 {
		perFile = 150
	}
	g := &gen{l: l, fset: l.Fset, untranslatedCounts: map[string]int{}, anyVariants: map[string]int{}}

	// tests/util.go: package-level variables (the functions are ported by hand in tests/util.rs).
	utilCode := g.genUtil(l.Util)

	var files []fileOut
	modNames := map[string]bool{}
	fileMods := map[*ast.File]string{}
	for _, p := range l.Tests {
		for i, f := range p.Files {
			name := p.Names[i]
			if name == "testmain_test.go" {
				continue
			}
			mod := moduleName(name)
			for modNames[mod] {
				mod += "_"
			}
			modNames[mod] = true
			fileMods[f] = mod
			for _, d := range f.Decls {
				switch d := d.(type) {
				case *ast.FuncDecl:
					objModule[p.Info.Defs[d.Name]] = mod
				case *ast.GenDecl:
					for _, sp := range d.Specs {
						switch sp := sp.(type) {
						case *ast.ValueSpec:
							for _, n := range sp.Names {
								objModule[p.Info.Defs[n]] = mod
							}
						case *ast.TypeSpec:
							objModule[p.Info.Defs[sp.Name]] = mod
						}
					}
				}
			}
		}
	}
	for _, p := range l.Tests {
		for i, f := range p.Files {
			if mod, ok := fileMods[f]; ok {
				files = append(files, g.genFile(p, f, p.Names[i], mod))
			}
		}
	}
	sort.Slice(files, func(i, j int) bool { return files[i].module < files[j].module })
	moduleChunk := map[string]string{}

	genDir := filepath.Join(out, "gen")
	if err := os.RemoveAll(genDir); err != nil {
		return err
	}
	if err := os.MkdirAll(genDir, 0o755); err != nil {
		return err
	}
	header := "// Code generated by tools/gen-fourslash from ts-ref/tsc/internal/fourslash/tests. DO NOT EDIT.\n\n"
	var mod strings.Builder
	mod.WriteString(header)
	var reg strings.Builder
	nTests, nSkip := 0, 0
	// chunks: consecutive files, about perFile tests each
	type span struct{ start, end int }
	var chunks []span
	for start := 0; start < len(files); {
		count := 0
		end := start
		for end < len(files) && (count == 0 || count+len(files[end].tests) <= perFile) {
			count += len(files[end].tests)
			end++
		}
		for _, f := range files[start:end] {
			moduleChunk[f.module] = fmt.Sprintf("gen_%02d", len(chunks))
		}
		chunks = append(chunks, span{start, end})
		start = end
	}
	chunk := 0
	for ; chunk < len(chunks); chunk++ {
		start, end := chunks[chunk].start, chunks[chunk].end
		var b strings.Builder
		b.WriteString(header)
		b.WriteString("// `var x T` is zero-initialized as in Go, even where every branch assigns it before use.\n#![allow(unused_assignments)]\n\n")
		chunkName := fmt.Sprintf("gen_%02d", chunk)
		for _, f := range files[start:end] {
			f.code = modRefRe.ReplaceAllStringFunc(f.code, func(m string) string {
				mod := modRefRe.FindStringSubmatch(m)[1]
				return "crate::tests::gen::" + moduleChunk[mod] + "::" + mod + "::"
			})
			fmt.Fprintf(&b, "pub mod %s {\nuse crate::tests::prelude::*;\n\n%s}\n\n", f.module, f.code)
			for _, te := range f.tests {
				skip := "None"
				if te.skipped {
					s, _ := rustStr(te.skip)
					skip = "Some(" + s + ")"
					nSkip++
				}
				nTests++
				fmt.Fprintf(&reg, "    TestEntry { name: %q, file: %q, line: %d, func: %s::%s::%s, skip: %s },\n",
					te.goName, te.file, te.line, chunkName, f.module, te.fn, skip)
			}
		}
		if err := os.WriteFile(filepath.Join(genDir, chunkName+".rs"), []byte(b.String()), 0o644); err != nil {
			return err
		}
		fmt.Fprintf(&mod, "pub mod %s;\n", chunkName)
	}
	mod.WriteString("\nuse crate::runner::TestEntry;\n\n")
	fmt.Fprintf(&mod, "pub static REGISTRY: &[TestEntry] = &[\n%s];\n", reg.String())
	if err := os.WriteFile(filepath.Join(genDir, "mod.rs"), []byte(mod.String()), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(out, "util_gen.rs"), []byte(header+utilCode), 0o644); err != nil {
		return err
	}

	fmt.Printf("generated %d tests (%d known failing) in %d files\n", nTests, nSkip, chunk)
	if len(g.untranslatedCounts) == 0 {
		fmt.Println("untranslated constructs: none")
	} else {
		fmt.Println("untranslated constructs:")
		var ks []string
		for k := range g.untranslatedCounts {
			ks = append(ks, k)
		}
		sort.Slice(ks, func(i, j int) bool {
			if g.untranslatedCounts[ks[i]] != g.untranslatedCounts[ks[j]] {
				return g.untranslatedCounts[ks[i]] > g.untranslatedCounts[ks[j]]
			}
			return ks[i] < ks[j]
		})
		for _, k := range ks {
			fmt.Printf("%6d %s\n", g.untranslatedCounts[k], k)
		}
	}
	return nil
}

func moduleName(file string) string {
	m := ident(strings.Map(func(r rune) rune {
		if r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			return r
		}
		return '_'
	}, strings.TrimSuffix(file, "_test.go")))
	for strings.Contains(m, "__") {
		m = strings.ReplaceAll(m, "__", "_")
	}
	return m
}

func (g *gen) setPackage(p *Package) {
	if g.p != p {
		g.used = make(map[types.Object]bool, len(p.Info.Uses))
		for _, obj := range p.Info.Uses {
			g.used[obj] = true
		}
	}
	g.p = p
	g.info = p.Info
	curPkgPath = p.Path
}

// genUtil emits the package-level variables of tests/util/util.go as statics.
func (g *gen) genUtil(p *Package) string {
	g.setPackage(p)
	curModule = ""
	var b strings.Builder
	b.WriteString("use crate::tests::prelude::*;\nuse crate::tests::util::*;\n\n")
	for _, d := range p.Files[0].Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			continue
		}
		for _, s := range gd.Specs {
			vs := s.(*ast.ValueSpec)
			for i, n := range vs.Names {
				obj := g.info.Defs[n]
				code := g.protect(func() string {
					return g.expr(vs.Values[i], obj.Type(), mOwned)
				})
				if code == "" {
					fmt.Fprintf(&b, "// util.go: %s untranslated\n", n.Name)
					continue
				}
				pos := g.pos(n)
				fmt.Fprintf(&b, "// util.go:%d\npub static %s: LazyLock<%s> = LazyLock::new(|| %s);\n\n", pos.Line, screaming(n.Name), rtype(obj.Type(), false), code)
			}
		}
	}
	return b.String()
}

// protect runs a translation and returns "" (recording the construct) if it hits something untranslatable.
func (g *gen) protect(fn func() string) (s string) {
	defer func() {
		if r := recover(); r != nil {
			u, ok := r.(untranslated)
			if !ok {
				panic(r)
			}
			g.untranslatedCounts[u.what]++
			s = ""
		}
	}()
	return fn()
}

func (g *gen) genFile(p *Package, f *ast.File, name, mod string) fileOut {
	g.setPackage(p)
	curModule = mod
	fo := fileOut{module: mod}
	var b strings.Builder
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			isTest := strings.HasPrefix(d.Name.Name, "Test") && d.Recv == nil && d.Type.Params.NumFields() == 1
			code, skip, skipped, err := g.genFunc(d, isTest)
			pos := g.pos(d)
			if err != "" {
				g.untranslatedCounts[err]++
				if isTest {
					code = sprintf("// %s:%d\npub fn %s(t: &T) {\n    go::untranslated(t, %q);\n}\n", name, pos.Line, ident(d.Name.Name), err)
				} else {
					code = sprintf("// %s:%d: %s untranslated (%s)\n", name, pos.Line, d.Name.Name, err)
				}
			}
			b.WriteString(code)
			b.WriteString("\n")
			if isTest {
				fo.tests = append(fo.tests, testEntry{goName: d.Name.Name, file: name, module: mod, fn: ident(d.Name.Name), skip: skip, skipped: skipped, line: pos.Line})
			}
		case *ast.GenDecl:
			if d.Tok == token.IMPORT {
				continue
			}
			code := g.protect(func() string { return g.genTopGenDecl(d) })
			if code == "" {
				code = sprintf("// %s:%d: declaration untranslated\n", name, g.pos(d).Line)
			}
			b.WriteString(code)
			b.WriteString("\n")
		}
	}
	// Not re-indented: multi-line raw strings must stay byte-exact.
	fo.code = b.String()
	return fo
}

func indentBlock(s string, n int) string {
	pre := strings.Repeat("    ", n)
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	for i, l := range lines {
		if l != "" {
			lines[i] = pre + l
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

func (g *gen) genTopGenDecl(d *ast.GenDecl) string {
	var b strings.Builder
	switch d.Tok {
	case token.CONST:
		for _, s := range d.Specs {
			vs := s.(*ast.ValueSpec)
			for _, n := range vs.Names {
				obj := g.info.Defs[n].(*types.Const)
				fmt.Fprintf(&b, "// %s:%d\npub const %s: %s = %s;\n", filepath.Base(g.pos(n).Filename), g.pos(n).Line, screaming(n.Name), constRType(obj.Type()), g.constLit(obj.Val(), obj.Type()))
			}
		}
	case token.VAR:
		for _, s := range d.Specs {
			vs := s.(*ast.ValueSpec)
			for i, n := range vs.Names {
				obj := g.info.Defs[n]
				g.vars = map[types.Object]*varInfo{}
				code := g.expr(vs.Values[i], obj.Type(), mOwned)
				fmt.Fprintf(&b, "// %s:%d\npub static %s: LazyLock<%s> = LazyLock::new(|| %s);\n", filepath.Base(g.pos(n).Filename), g.pos(n).Line, screaming(n.Name), rtype(obj.Type(), false), code)
			}
		}
	case token.TYPE:
		for _, s := range d.Specs {
			b.WriteString(g.genTypeSpec(s.(*ast.TypeSpec), "pub "))
		}
	}
	return b.String()
}

func constRType(t types.Type) string {
	if isString(t) {
		return "&str"
	}
	return rtype(t, false)
}

func (g *gen) genTypeSpec(ts *ast.TypeSpec, vis string) string {
	obj := g.info.Defs[ts.Name].(*types.TypeName)
	st, ok := obj.Type().Underlying().(*types.Struct)
	if !ok || ts.Assign.IsValid() {
		fail("type declaration %s", ts.Name.Name)
	}
	name := obj.Name()
	if g.localTypes == nil {
		g.localTypes = map[*types.TypeName]string{}
	}
	g.localTypes[obj] = name
	var b strings.Builder
	fmt.Fprintf(&b, "#[derive(Clone, Debug, Default)]\n%sstruct %s {\n", vis, name)
	for i := 0; i < st.NumFields(); i++ {
		fl := st.Field(i)
		fmt.Fprintf(&b, "    pub %s: %s,\n", ident(fl.Name()), g.fieldType(fl.Type()))
	}
	b.WriteString("}\n")
	return b.String()
}

func (g *gen) fieldType(t types.Type) string {
	if sig, ok := types.Unalias(t).(*types.Signature); ok {
		_ = sig
		fail("func-typed struct field")
	}
	return rtype(t, false)
}

// genFunc translates a top-level function. Returns the code, the t.Skip reason (if the test starts by skipping),
// or the untranslated construct.
func (g *gen) genFunc(d *ast.FuncDecl, isTest bool) (code string, skip string, skipped bool, err string) {
	defer func() {
		if r := recover(); r != nil {
			u, ok := r.(untranslated)
			if !ok {
				panic(r)
			}
			err = u.what
		}
	}()
	g.vars = map[types.Object]*varInfo{}
	g.curF, g.curT = "", ""
	g.tmp = 0
	g.assigned = map[types.Object]bool{}
	g.collectAssigned(d.Body)
	var b strings.Builder
	g.buf = &b
	g.indent = 0
	pos := g.pos(d)
	obj := g.info.Defs[d.Name].(*types.Func)
	sig := obj.Type().(*types.Signature)
	stmts := d.Body.List
	if isTest {
		// A leading `t.Skip(...)` (after `t.Parallel()`) registers the test as known failing instead.
		for i, s := range stmts {
			if i > 1 {
				break
			}
			if call, ok := isCallStmt(s); ok {
				if sel, ok := call.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Skip" && isTestingTPtr(g.info.TypeOf(sel.X)) {
					skipped = true
					if len(call.Args) == 1 {
						if tv := g.info.Types[call.Args[0]]; tv.Value != nil {
							skip = constString(tv.Value)
						}
					}
					stmts = append(append([]ast.Stmt{}, stmts[:i]...), stmts[i+1:]...)
					break
				}
			}
		}
	}
	g.resultTypes = nil
	for i := 0; i < sig.Results().Len(); i++ {
		g.resultTypes = append(g.resultTypes, sig.Results().At(i).Type())
	}
	g.inResultFunc = sig.Results().Len() > 0
	params, prologue := g.params(sig, d.Type.Params, false)
	ret := g.results(sig)
	fmt.Fprintf(&b, "// %s:%d\npub fn %s(%s)%s {\n", filepath.Base(pos.Filename), pos.Line, ident(d.Name.Name), strings.Join(params, ", "), ret)
	g.indent = 1
	for _, p := range prologue {
		g.line("%s", p)
	}
	resetAnonStructs()
	header := b.String()
	b.Reset()
	g.stmts(stmts)
	body := b.String()
	b.Reset()
	b.WriteString(header)
	for _, d := range anonStructDefs {
		b.WriteString(indentBlock(d, 1))
	}
	b.WriteString(body)
	g.indent = 0
	b.WriteString("}\n")
	return b.String(), skip, skipped, ""
}

func isCallStmt(s ast.Stmt) (*ast.CallExpr, bool) {
	es, ok := s.(*ast.ExprStmt)
	if !ok {
		return nil, false
	}
	c, ok := es.X.(*ast.CallExpr)
	return c, ok
}

// params declares the parameters of a function or closure. Parameters that the body assigns to are re-bound as
// owned values in the prologue.
func (g *gen) params(sig *types.Signature, fl *ast.FieldList, closure bool) (params []string, prologue []string) {
	i := 0
	for _, field := range fl.List {
		names := field.Names
		if len(names) == 0 {
			names = []*ast.Ident{nil}
		}
		for _, n := range names {
			v := sig.Params().At(i)
			i++
			t := v.Type()
			name := "_"
			if n != nil && n.Name != "_" {
				name = ident(n.Name)
			}
			rt := rtype(t, true)
			if sig.Variadic() && i == sig.Params().Len() {
				st := t.(*types.Slice)
				if isString(st.Elem()) {
					rt = "&[&str]"
				} else {
					rt = "&[" + elemType(st.Elem()) + "]"
				}
			}
			vi := &varInfo{name: name, kind: kPlace}
			switch {
			case isString(t):
				vi.kind = kStr
			case isStringSlice(t):
				vi.kind = kStrSlice
			case isSliceT(t):
				vi.kind = kSlice
			}
			if isFourslashTestPtr(t) {
				g.curF = name
			}
			if isTestingTPtr(t) {
				g.curT = name
			}
			if n != nil {
				if obj := g.info.Defs[n]; obj != nil {
					if !g.objectUsed(obj) {
						name = "_" + name
						vi.name = name
					}
					g.vars[obj] = vi
					if g.assigned[obj] && vi.kind == kPlace {
						prologue = append(prologue, sprintf("let mut %s = %s;", name, name))
					}
					if g.assigned[obj] && (vi.kind == kStr || vi.kind == kStrSlice || vi.kind == kSlice) {
						switch vi.kind {
						case kStr:
							prologue = append(prologue, sprintf("let mut %s = %s.to_string();", name, name))
						case kStrSlice:
							prologue = append(prologue, sprintf("let mut %s = go::owned_strs(%s);", name, name))
						case kSlice:
							prologue = append(prologue, sprintf("let mut %s = %s.to_vec();", name, name))
						}
						vi.kind = kPlace
					}
				}
			}
			params = append(params, name+": "+rt)
		}
	}
	return
}

func (g *gen) objectUsed(obj types.Object) bool {
	return g.used[obj]
}

func (g *gen) binding(name string, obj types.Object) string {
	if g.assigned[obj] || isFourslashTestPtr(obj.Type()) || isNamed(derefType(obj.Type()), "strings", "Builder") {
		return "mut " + name
	}
	return name
}

func isSliceT(t types.Type) bool { _, ok := isSlice(t); return ok }

func (g *gen) results(sig *types.Signature) string {
	r := sig.Results()
	if r.Len() == 0 {
		return ""
	}
	var ts []string
	for i := 0; i < r.Len(); i++ {
		ts = append(ts, g.resultType(r.At(i).Type()))
	}
	if len(ts) == 1 {
		return " -> " + ts[0]
	}
	return " -> (" + strings.Join(ts, ", ") + ")"
}

func (g *gen) resultType(t types.Type) string {
	if sig, ok := types.Unalias(t).(*types.Signature); ok {
		if sig.Params().Len() == 0 && sig.Results().Len() == 0 {
			return "fourslash::DoneFn"
		}
		fail("func result type")
	}
	return rtype(t, false)
}

func (g *gen) collectAssigned(n ast.Node) {
	ast.Inspect(n, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.AssignStmt:
			if n.Tok != token.DEFINE {
				for _, l := range n.Lhs {
					if o := g.assignedObject(l); o != nil {
						g.assigned[o] = true
					}
				}
			}
		case *ast.IncDecStmt:
			if o := g.assignedObject(n.X); o != nil {
				g.assigned[o] = true
			}
		}
		return true
	})
}

func (g *gen) assignedObject(e ast.Expr) types.Object {
	for {
		switch x := e.(type) {
		case *ast.Ident:
			return g.info.Uses[x]
		case *ast.SelectorExpr:
			e = x.X
		case *ast.IndexExpr:
			e = x.X
		case *ast.StarExpr:
			e = x.X
		case *ast.ParenExpr:
			e = x.X
		default:
			return nil
		}
	}
}

func constString(v interface{ ExactString() string }) string {
	s := v.ExactString()
	if uq, err := unquote(s); err == nil {
		return uq
	}
	return s
}
