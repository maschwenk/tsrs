#!/usr/bin/env python3
"""Generate option declarations, change comparisons, and runner variations from the pinned Go source."""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / 'ts-ref'
OPTIONS = REF / 'tsc/internal/tsoptions'
MODEL = REF / 'tools/scripts/tsc/options.ts'


def snake(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower()


subprocess.run(['python3', str(ROOT / 'tools/gen-tsoptions/gen_decls.py'), str(OPTIONS / 'declarations_generated.go'), str(ROOT / 'crates/tsrs_tsoptions/src/declscompiler.rs'), 'commonOptionsWithBuild,optionsForCompiler', str(MODEL)], check=True)
source = (OPTIONS / 'options_generated.go').read_text()
output = '// @generated by tools/gen-tsoptions/gen.py from pinned tsoptions/options_generated.go.\nuse tsrs_core::CompilerOptions;\n\n'
for name in ['CompilerOptionsAffectSemanticDiagnostics', 'CompilerOptionsAffectDeclarationPath', 'CompilerOptionsAffectEmit']:
    body = re.search(r'^func ' + name + r'\([^\n]+\) bool \{\n([\s\S]*?)\n\}', source, re.M).group(1)
    expression = body[body.index('\treturn oldOptions.'):].removeprefix('\treturn ').strip()
    expression = re.sub(r'\b(?:oldOptions|newOptions)\b', lambda m: snake(m[0]), expression)
    expression = re.sub(r'\.([A-Z]\w*)', lambda m: '.' + snake(m[1]), expression)
    if name == 'CompilerOptionsAffectSemanticDiagnostics':
        output += '#[expect(clippy::suspicious_operation_groupings, reason = "Each receiver reads its own strict option, matching the pinned Go comparisons.")]\n'
    output += f'''pub fn {snake(name)}(old_options: Option<&CompilerOptions>, new_options: Option<&CompilerOptions>) -> bool {{
    let (old_options, new_options) = match (old_options, new_options) {{
        (None, None) => return false,
        (Some(old), Some(new)) if std::ptr::eq(old, new) => return false,
        (Some(old), Some(new)) => (old, new),
        _ => return true,
    }};
    {expression}
}}

'''
(ROOT / 'crates/tsrs_tsoptions/src/options_generated.rs').write_text(output)
source = (REF / 'tsc/internal/testrunner/options_generated.go').read_text()
values = re.findall(r'^\s*"([a-z]+)",$', source, re.M)
assert values
(ROOT / 'crates/tsrs_testrunner/src/options_generated.rs').write_text('// @generated by tools/gen-tsoptions/gen.py from pinned testrunner/options_generated.go.\npub const COMPILER_VARY_BY: &[&str] = &[\n' + ''.join(f'    "{value}",\n' for value in values) + '];\n')
