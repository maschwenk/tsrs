// Generates crates/tsrs_ast/src/{kind,nodeflags,tokenflags,modifierflags,symbolflags,checkflags,functionflags}.rs
// from the Go sources in ts-ref/tsc/internal/ast. Run: node tools/gen-ast/gen-flags.ts
import * as fs from "node:fs";
import * as path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const goDir = path.join(root, "ts-ref/tsc/internal/ast");
const outDir = path.join(root, "crates/tsrs_ast/src");
const header = "// Code generated by tools/gen-ast/gen-flags.ts. DO NOT EDIT.\n\n";

function genKind() {
    const src = fs.readFileSync(path.join(goDir, "kind_generated.go"), "utf8");
    const constBlock = src.slice(src.indexOf("const ("), src.indexOf("\n)\n", src.indexOf("const (")));
    const variants: string[] = [];
    const consts: [string, string][] = [];
    for (const raw of constBlock.split("\n").slice(1)) {
        const line = raw.trim();
        if (!line) continue;
        if (line.startsWith("//")) { variants.push("    " + line); continue; }
        const [code, ...rest] = line.split("//");
        const comment = rest.length ? " //" + rest.join("//") : "";
        const m = /^Kind(\w+)(?:\s+Kind)?(?:\s*=\s*(\w+))?$/.exec(code.trim());
        if (!m) throw new Error("bad kind line: " + line);
        if (m[2] && m[2] !== "iota") consts.push([m[1], m[2].replace(/^Kind/, "")]);
        else variants.push(`    ${m[1]},${comment}`);
    }
    let out = header;
    out += "#[repr(i16)]\n#[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Debug, Default)]\npub enum Kind {\n";
    out += variants.map((v, i) => i === 0 ? v.replace("Unknown,", "#[default]\n    Unknown,") : v).join("\n") + "\n}\n\n";
    out += "impl Kind {\n";
    for (const [n, v] of consts) out += `    pub const ${n}: Kind = Kind::${v};\n`;
    out += "\n    #[inline]\n    pub fn from_i16(v: i16) -> Kind {\n        assert!(v >= 0 && v <= Kind::Count as i16);\n        // SAFETY: Kind is repr(i16) with contiguous discriminants 0..=Count.\n        unsafe { std::mem::transmute::<i16, Kind>(v) }\n    }\n}\n\n";
    const aliases = src.slice(src.indexOf("type ("));
    for (const m of aliases.matchAll(/^\t(\w+)\s+= Kind(.*)$/gm)) out += `pub type ${m[1]} = Kind;\n`;
    fs.writeFileSync(path.join(outDir, "kind.rs"), out);
}

function convertExpr(expr: string, prefix: string): string {
    let e = expr.trim();
    e = e.replace(/1<<30 - 1/, "(1 << 30) - 1");
    e = e.replace(new RegExp(`\\b${prefix}(\\w+)`, "g"), "Self::$1.bits()");
    e = e.replace(/& \^/g, "& !").replace(/(^|[\s(])\^/g, "$1!");
    return e;
}

function genFlags(file: string, typeName: string) {
    const src = fs.readFileSync(path.join(goDir, file + ".go"), "utf8");
    const typeM = new RegExp(`type ${typeName} (\\w+)`).exec(src)!;
    const rustInt = ({ uint32: "u32", int32: "i32", uint64: "u64", int64: "i64" } as Record<string, string>)[typeM[1]];
    const start = src.indexOf("const (");
    const block = src.slice(start + 7, src.indexOf("\n)\n", start));
    let out = header + "use bitflags::bitflags;\n\nbitflags! {\n";
    out += `    #[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Debug, Default)]\n    pub struct ${typeName}: ${rustInt} {\n`;
    for (const raw of block.split("\n")) {
        const line = raw.trim();
        if (!line) { out += "\n"; continue; }
        if (line.startsWith("//")) { out += "        " + line + "\n"; continue; }
        const idx = line.indexOf("//");
        const code = idx >= 0 ? line.slice(0, idx) : line;
        const comment = idx >= 0 ? " " + line.slice(idx) : "";
        const m = new RegExp(`^${typeName.replace("Flags", "Flags")}(\\w+)(?:\\s+${typeName})?\\s*=\\s*(.*)$`).exec(code.trim());
        if (!m) throw new Error(`bad line in ${file}: ${line}`);
        out += `        const ${m[1]} = ${convertExpr(m[2], typeName)};${comment}\n`;
    }
    out += "    }\n}\n";
    fs.writeFileSync(path.join(outDir, file + ".rs"), out.replace(/\n\n\n+/g, "\n\n").replace(/\{\n\n/g, "{\n").replace(/\n\n    \}/g, "\n    }"));
}

genKind();
genFlags("nodeflags", "NodeFlags");
genFlags("tokenflags", "TokenFlags");
genFlags("modifierflags", "ModifierFlags");
genFlags("symbolflags", "SymbolFlags");
genFlags("checkflags", "CheckFlags");
genFlags("functionflags", "FunctionFlags");
fs.appendFileSync(path.join(outDir, "functionflags.rs"), `
use tsrs_core::P;

use crate::ast::Node;
use crate::kind::Kind;
use crate::modifierflags::ModifierFlags;

pub fn get_function_flags(node: Option<P<Node>>) -> FunctionFlags {
    let Some(node) = node else {
        return FunctionFlags::Invalid;
    };
    let Some(data) = node.body_data() else {
        return FunctionFlags::Invalid;
    };
    let mut flags = FunctionFlags::Normal;
    match node.kind() {
        Kind::FunctionDeclaration | Kind::FunctionExpression | Kind::MethodDeclaration | Kind::ArrowFunction => {
            if node.kind() != Kind::ArrowFunction && data.asterisk_token.is_some() {
                flags |= FunctionFlags::Generator;
            }
            if crate::has_syntactic_modifier(node, ModifierFlags::Async) {
                flags |= FunctionFlags::Async;
            }
        }
        _ => {}
    }
    if data.body.is_none() {
        flags |= FunctionFlags::Invalid;
    }
    flags
}
`);
