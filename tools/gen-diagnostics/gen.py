#!/usr/bin/env python3
"""Generate crates/tsrs_diagnostics/src/generated.rs from the Go
ts-ref/tsc/internal/diagnostics/diagnostics_generated.go, so the Rust
identifiers, codes, keys, texts and flags match Go exactly.

Usage: python3 tools/gen-diagnostics/gen.py   (from the repo root)
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GO_FILE = os.path.join(ROOT, "ts-ref", "tsc", "internal", "diagnostics", "diagnostics_generated.go")
OUT_FILE = os.path.join(ROOT, "crates", "tsrs_diagnostics", "src", "generated.rs")

GO_STR = r'"(?:[^"\\]|\\.)*"'
VAR_RE = re.compile(
    r'^var (\w+) = &Message\{code: (\d+), category: Category(\w+), key: (' + GO_STR + r'), text: (' + GO_STR + r')((?:, \w+: true)*)\}$'
)
FLAG_RE = re.compile(r', (\w+): true')
FLAGS = ["reportsUnnecessary", "elidedInCompatibilityPyramid", "reportsDeprecated"]
RUST_FLAG = {
    "reportsUnnecessary": "reports_unnecessary",
    "elidedInCompatibilityPyramid": "elided_in_compatibility_pyramid",
    "reportsDeprecated": "reports_deprecated",
}
CATEGORIES = {"Warning", "Error", "Suggestion", "Message"}
RUST_KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl",
    "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static",
    "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn",
    "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual",
    "yield", "try", "gen",
}


def go_unquote(s):
    # The Go generator emits %q; only \" and \\ escapes occur, which JSON decodes identically.
    for esc in re.findall(r'\\.', s[1:-1]):
        if esc not in ('\\"', '\\\\'):
            sys.exit("unsupported Go escape %s in %s" % (esc, s))
    return json.loads(s)


def rust_quote(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main():
    with open(GO_FILE, encoding="utf-8") as f:
        lines = f.read().split("\n")

    messages = []
    all_order = []
    in_all = False
    for line in lines:
        if line.startswith("var allMessages = "):
            in_all = True
            continue
        if in_all:
            if line == "}":
                in_all = False
                continue
            m = re.fullmatch(r"\t&(\w+),", line)
            if not m:
                sys.exit("unexpected allMessages line: " + line)
            all_order.append(m.group(1))
            continue
        if line.startswith("var "):
            m = VAR_RE.match(line)
            if not m:
                sys.exit("unparsed var line: " + line)
            name, code, category, key, text, flags = m.groups()
            if category not in CATEGORIES:
                sys.exit("unknown category " + category)
            if name in RUST_KEYWORDS:
                sys.exit("identifier is a Rust keyword: " + name)
            flag_names = FLAG_RE.findall(flags)
            for fl in flag_names:
                if fl not in FLAGS:
                    sys.exit("unknown flag " + fl)
            messages.append((name, int(code), category, go_unquote(key), go_unquote(text), set(flag_names)))

    names = [m[0] for m in messages]
    if names != all_order:
        sys.exit("allMessages order does not match var declarations")
    if len(set(names)) != len(names):
        sys.exit("duplicate identifiers")

    out = ["// Code generated by tools/gen-diagnostics/gen.py from diagnostics_generated.go; DO NOT EDIT.", "",
           "use crate::{Category, Key, Message};", ""]
    for name, code, category, key, text, flags in messages:
        fields = ", ".join("%s: %s" % (RUST_FLAG[fl], "true" if fl in flags else "false") for fl in FLAGS)
        out.append(
            "pub static %s: Message = Message { code: %d, category: Category::%s, key: Key(%s), text: %s, %s };"
            % (name, code, category, rust_quote(key), rust_quote(text), fields)
        )
        out.append("")
    out.append("pub(crate) static ALL_MESSAGES: [&Message; %d] = [" % len(messages))
    for name in names:
        out.append("    &%s," % name)
    out.append("];")
    out.append("")

    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote %d messages to %s" % (len(messages), os.path.relpath(OUT_FILE, ROOT)))


if __name__ == "__main__":
    main()
