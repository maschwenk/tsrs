#!/usr/bin/env python3
"""Lint ratchet: the number of clippy findings per (lint, file) may not grow. docs/RUST.md has the rules.

  tools/lint/ratchet.py                  check; exit 1 if a (lint, file) has more findings than baseline.tsv
  tools/lint/ratchet.py --update         lower baseline.tsv to the current counts (after fixing findings)
                                         rows for code that is compiled differently on another OS are kept
  tools/lint/ratchet.py --update --allow-increase
                                         also raise counts; only for a TOOLCHAIN bump or a new lint
  tools/lint/ratchet.py --list LINT      print every current finding of one lint (e.g. clippy::redundant_clone)
  tools/lint/ratchet.py --self-test      check the comparison logic without running cargo

The lint set is [workspace.lints.clippy] in Cargo.toml plus clippy.toml, plus RUSTC_LINTS below.
"""

import json
import os
import re
import subprocess
import sys

# Findings depend on the clippy version, so the ratchet runs one pinned toolchain everywhere (CI installs it too).
# docs/RUST.md says how to bump it.
TOOLCHAIN = "1.99.0"

# Generated code (tools/gen-fourslash), 750k lines. Generated files in other crates are skipped by `generated`.
EXCLUDE = ["tsrs_fourslash"]

# rustc lints the ratchet adds on the command line. They cannot be "warn" in [workspace.lints.rust] while existing
# findings remain: `cargo check` runs with -D warnings.
RUSTC_LINTS = ["unsafe_op_in_unsafe_fn"]

# unsafe_op_in_unsafe_fn reports under its error code in edition 2021.
CODE_ALIASES = {"E0133": "unsafe_op_in_unsafe_fn"}

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASELINE = os.path.join(ROOT, "tools", "lint", "baseline.tsv")


def cargo_command():
    pinned = ["cargo", "+" + TOOLCHAIN]
    probe = subprocess.run(pinned + ["clippy", "--version"], capture_output=True, text=True, cwd=ROOT)
    if probe.returncode == 0:
        return pinned
    probe = subprocess.run(["cargo", "clippy", "--version"], capture_output=True, text=True, cwd=ROOT)
    minor = TOOLCHAIN.split(".")[1]
    if probe.returncode == 0 and re.match(r"clippy 0\.1\.%s\b" % minor, probe.stdout):
        return ["cargo"]
    sys.exit(
        "lint ratchet: needs clippy from Rust %s (findings differ between versions). Install it with:\n"
        "  rustup toolchain install %s --profile minimal --component clippy" % (TOOLCHAIN, TOOLCHAIN)
    )


GENERATED = {}


def generated(file):
    """Whether the file starts with a `// Code generated by ...; DO NOT EDIT.` line: its findings are the generator's."""
    if file not in GENERATED:
        try:
            first = open(os.path.join(ROOT, file), errors="replace").readline()
        except OSError:
            first = ""
        GENERATED[file] = "Code generated" in first and "DO NOT EDIT" in first
    return GENERATED[file]


def workspace_file(span):
    """The file a finding is charged to: the span itself, or the macro call site when the span is outside the repo."""
    while span is not None:
        name = span["file_name"].replace("\\", "/")
        if name.startswith(ROOT + "/"):
            name = name[len(ROOT) + 1:]
        if not os.path.isabs(name):
            return name, span["line_start"], span["column_start"]
        span = (span.get("expansion") or {}).get("span")
    return None


def dep_info_sources(artifact):
    """The workspace .rs files rustc read for one compiled crate, from the dep-info file next to its .rmeta."""
    directory, name = os.path.split(artifact)
    dep_info = os.path.join(directory, re.sub(r"^lib", "", os.path.splitext(name)[0]) + ".d")
    if not os.path.exists(dep_info):
        return set()
    sources = open(dep_info).readline().split(": ", 1)[-1]
    files = set()
    for source in re.split(r"(?<!\\) ", sources.strip()):
        source = source.replace("\\ ", " ").replace("\\", "/")
        if source.startswith(ROOT + "/"):
            source = source[len(ROOT) + 1:]
        if source.endswith(".rs") and not os.path.isabs(source):
            files.add(source)
    return files


def run_clippy():
    """Returns (findings, compiled): findings are (lint, file, line, column, message); compiled is the set of
    workspace source files that were part of the build on this platform."""
    cmd = cargo_command() + ["clippy", "--workspace", "--locked", "--message-format=json"]
    for crate in EXCLUDE:
        cmd += ["--exclude", crate]
    cmd.append("--")
    for lint in RUSTC_LINTS:
        cmd += ["-W", lint]
    proc = subprocess.Popen(cmd, cwd=ROOT, stdout=subprocess.PIPE, text=True)
    seen = set()
    compiled = set()
    for line in proc.stdout:
        if not line.startswith("{"):
            continue
        record = json.loads(line)
        if record.get("reason") == "compiler-artifact":
            for artifact in record.get("filenames", []):
                if artifact.endswith(".rmeta"):
                    compiled |= dep_info_sources(artifact)
        if record.get("reason") != "compiler-message":
            continue
        message = record["message"]
        code = (message.get("code") or {}).get("code")
        if message.get("level") not in ("warning", "error"):
            continue
        if code is None:
            if message.get("level") == "error":
                sys.stderr.write(message.get("rendered") or message["message"])
            continue
        primary = [s for s in message.get("spans", []) if s.get("is_primary")] or message.get("spans", [])
        where = workspace_file(primary[0]) if primary else None
        if where is None or generated(where[0]):
            continue
        seen.add((CODE_ALIASES.get(code, code), where[0], where[1], where[2], message["message"]))
    if proc.wait() != 0:
        sys.exit("lint ratchet: `%s` failed; fix the build first" % " ".join(cmd))
    return sorted(seen), compiled


def count(findings):
    counts = {}
    for lint, file, _line, _column, _message in findings:
        counts[(lint, file)] = counts.get((lint, file), 0) + 1
    return counts


def parse_baseline(text):
    counts = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        number, lint, file = line.split("\t")
        counts[(lint, file)] = int(number)
    return counts


def render_baseline(counts):
    lines = [
        "# Lint ratchet baseline: findings that predate the ratchet, as count<TAB>lint<TAB>file.",
        "# Written by `tools/lint/ratchet.py --update` with clippy from Rust %s. Counts only go down; never edit by hand."
        % TOOLCHAIN,
    ]
    for (lint, file), number in sorted(counts.items()):
        if number > 0:
            lines.append("%d\t%s\t%s" % (number, lint, file))
    return "\n".join(lines) + "\n"


def grown_keys(baseline, current):
    """The (lint, file) keys with more findings than the baseline allows."""
    return sorted(key for key, number in current.items() if number > baseline.get(key, 0))


PLATFORM_CFG = re.compile(
    r"cfg(_attr)?\([^\n]*\b(target_os|target_family|target_arch|target_env|target_vendor|target_pointer_width|unix|windows)\b"
)


def platform_gated(file):
    return bool(PLATFORM_CFG.search(open(os.path.join(ROOT, file), errors="replace").read()))


def updated(baseline, current, compiled, exists, gated):
    """The baseline after `--update`: current counts, except that a count is not lowered when another platform
    may still have the findings (the file is not compiled here, or it has platform `cfg`s). Returns (counts, kept)."""
    counts, kept = {}, []
    for key in sorted(set(baseline) | set(current)):
        before, now = baseline.get(key, 0), current.get(key, 0)
        file = key[1]
        if now < before and exists(file) and (file not in compiled or gated(file)):
            counts[key] = before
            kept.append(key)
        else:
            counts[key] = now
    return counts, kept


def changed_lines(file):
    """Line numbers of `file` that differ from the merge base with origin/main, or None when git cannot tell."""
    base = subprocess.run(["git", "merge-base", "HEAD", "origin/main"], capture_output=True, text=True, cwd=ROOT)
    if base.returncode != 0:
        return None
    diff = subprocess.run(
        ["git", "diff", "-U0", "--no-color", base.stdout.strip(), "--", file], capture_output=True, text=True, cwd=ROOT
    )
    if diff.returncode != 0:
        return None
    lines = set()
    for start, length in re.findall(r"^@@ -\S+ \+(\d+)(?:,(\d+))? @@", diff.stdout, re.M):
        lines.update(range(int(start), int(start) + int(length or 1)))
    return lines


def report_grown(grown, baseline, current, findings):
    total = sum(current[key] - baseline.get(key, 0) for key in grown)
    print("lint ratchet: %d new finding%s\n" % (total, "" if total == 1 else "s"))
    for lint, file in grown:
        print("%s  %s  (baseline %d, now %d)" % (lint, file, baseline.get((lint, file), 0), current[(lint, file)]))
        here = [f for f in findings if f[0] == lint and f[1] == file]
        touched = changed_lines(file)
        on_changed = [f for f in here if touched and f[2] in touched]
        for _lint, _file, line, column, message in on_changed or here:
            print("  %s:%d:%d  %s" % (file, line, column, message))
        if not on_changed and len(here) > current[(lint, file)] - baseline.get((lint, file), 0):
            print("  (all findings in the file are listed; the new one is among them)")
        print()
    print(
        "Fix the new findings. If the flagged code is intended, put\n"
        '  #[expect(<lint>, reason = "<why this is needed here>")]\n'
        "on the item or statement. Do not raise tools/lint/baseline.tsv. See docs/RUST.md."
    )


def self_test():
    baseline = {("clippy::a", "x.rs"): 2, ("clippy::b", "y.rs"): 1}
    assert grown_keys(baseline, dict(baseline)) == []
    assert grown_keys(baseline, {("clippy::a", "x.rs"): 3, ("clippy::b", "y.rs"): 1}) == [("clippy::a", "x.rs")]
    assert grown_keys(baseline, {("clippy::a", "x.rs"): 2, ("clippy::a", "z.rs"): 1}) == [("clippy::a", "z.rs")]
    assert grown_keys(baseline, {("clippy::a", "x.rs"): 1}) == []
    # One fixed and one added is still a failure.
    assert grown_keys(baseline, {("clippy::a", "x.rs"): 1, ("clippy::b", "y.rs"): 2}) == [("clippy::b", "y.rs")]
    assert parse_baseline(render_baseline(baseline)) == baseline
    assert parse_baseline(render_baseline({("clippy::a", "x.rs"): 0})) == {}
    findings = [("clippy::a", "x.rs", 1, 1, "m"), ("clippy::a", "x.rs", 9, 1, "m"), ("clippy::b", "y.rs", 2, 3, "n")]
    assert count(findings) == baseline
    # --update keeps a count that fell only because this platform does not build the code.
    base = {("clippy::a", "mac_only.rs"): 2, ("clippy::a", "has_cfg.rs"): 3, ("clippy::a", "plain.rs"): 4, ("clippy::a", "gone.rs"): 1}
    counts, kept = updated(
        base,
        {("clippy::a", "has_cfg.rs"): 1, ("clippy::a", "plain.rs"): 1},
        compiled={"has_cfg.rs", "plain.rs"},
        exists=lambda file: file != "gone.rs",
        gated=lambda file: file == "has_cfg.rs",
    )
    assert counts == {("clippy::a", "mac_only.rs"): 2, ("clippy::a", "has_cfg.rs"): 3, ("clippy::a", "plain.rs"): 1, ("clippy::a", "gone.rs"): 0}
    assert kept == [("clippy::a", "has_cfg.rs"), ("clippy::a", "mac_only.rs")]
    print("lint ratchet self-test: ok")


def main(argv):
    if "--self-test" in argv:
        return self_test()
    unknown = [a for a in argv if a.startswith("--") and a not in ("--update", "--allow-increase", "--list")]
    if unknown:
        sys.exit(__doc__)

    findings, compiled = run_clippy()
    current = count(findings)

    if "--list" in argv:
        lint = argv[argv.index("--list") + 1]
        for found, file, line, column, message in findings:
            if found == lint:
                print("%s:%d:%d  %s" % (file, line, column, message))
        return

    baseline = parse_baseline(open(BASELINE).read()) if os.path.exists(BASELINE) else {}
    grown = grown_keys(baseline, current)
    counts, kept = updated(
        baseline, current, compiled, exists=lambda file: os.path.exists(os.path.join(ROOT, file)), gated=platform_gated
    )

    if "--update" in argv:
        if grown and "--allow-increase" not in argv:
            report_grown(grown, baseline, current, findings)
            sys.exit("\nlint ratchet: --update only lowers counts (see --allow-increase)")
        with open(BASELINE, "w") as out:
            out.write(render_baseline(counts))
        rows = sum(1 for number in counts.values() if number)
        print("lint ratchet: baseline.tsv now holds %d findings in %d (lint, file) rows" % (sum(counts.values()), rows))
        if kept:
            print(
                "%d rows were not lowered. A file that is not compiled on this OS is lowered by --update on the OS that\n"
                "compiles it; a file with platform cfgs only by hand, after checking the other OS:" % len(kept)
            )
            for lint, file in kept:
                print("  %s  %s  (baseline %d, here %d)" % (lint, file, baseline[(lint, file)], current.get((lint, file), 0)))
        return

    if grown:
        report_grown(grown, baseline, current, findings)
        sys.exit(1)
    print("lint ratchet: ok (%d findings, none new)" % sum(current.values()))
    fixed = sum(baseline.values()) - sum(counts.values())
    if fixed > 0:
        print("%d baseline finding%s gone; run `tools/lint/ratchet.py --update` to lock that in" % (fixed, " is" if fixed == 1 else "s are"))


if __name__ == "__main__":
    main(sys.argv[1:])
