#!/usr/bin/env python3
"""Copy the bundled lib files from ts-ref/tsc/internal/bundled/libs into
crates/tsrs_vfs/libs and generate crates/tsrs_vfs/src/bundled/libs_generated.rs
and embed_generated.rs (the Rust equivalents of bundled/generate.go's
libs_generated.go and embed_generated.go).

Usage: python3 tools/gen-libs/gen.py   (from the repo root)
"""

import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GO_BUNDLED = os.path.join(ROOT, "ts-ref", "tsc", "internal", "bundled")
SRC_LIBS = os.path.join(GO_BUNDLED, "libs")
COPYRIGHT = os.path.join(GO_BUNDLED, "CopyrightNotice.txt")
CRATE = os.path.join(ROOT, "crates", "tsrs_vfs")
DST_LIBS = os.path.join(CRATE, "libs")
OUT_DIR = os.path.join(CRATE, "src", "bundled")


def fatal(msg):
    print(msg, file=sys.stderr)
    sys.exit(1)


def read_libs():
    with open(COPYRIGHT, "rb") as f:
        copyright = f.read()
    if b"\r" in copyright or not copyright.endswith(b"\n\n"):
        fatal("CopyrightNotice.txt must use LF line endings and end with a blank line")
    header = copyright + b"\n"

    libs = []
    for name in sorted(os.listdir(SRC_LIBS)):
        path = os.path.join(SRC_LIBS, name)
        if os.path.isdir(path) or not name.startswith("lib.") or not name.endswith(".d.ts"):
            fatal(f"unexpected entry in libs: {name}")
        with open(path, "rb") as f:
            content = f.read()
        if b"\r" in content:
            fatal(f"{path} must use LF line endings")
        if not content.startswith(header):
            fatal(f"{path} must start with CopyrightNotice.txt followed by a blank line")
        if not content.endswith(b"\n"):
            fatal(f"{path} must end with a newline")
        libs.append(name)
    return libs


def copy_libs(libs):
    if os.path.isdir(DST_LIBS):
        shutil.rmtree(DST_LIBS)
    os.makedirs(DST_LIBS)
    for name in libs:
        shutil.copyfile(os.path.join(SRC_LIBS, name), os.path.join(DST_LIBS, name))


def generate_lib_list(libs):
    out = ["// Code generated by tools/gen-libs/gen.py; DO NOT EDIT.", ""]
    out.append("// LIB_NAMES is the list of all bundled lib files, sorted by name.")
    out.append("// For the list of libs sorted by load order, use tsoptions::LIBS.")
    out.append("pub static LIB_NAMES: &[&str] = &[")
    for lib in libs:
        out.append(f'    "{lib}",')
    out.append("];")
    write(os.path.join(OUT_DIR, "libs_generated.rs"), out)


def generate_embedded(libs):
    out = ["// Code generated by tools/gen-libs/gen.py; DO NOT EDIT.", ""]
    out.append("pub(crate) static EMBEDDED_CONTENTS: &[(&str, &str)] = &[")
    for lib in libs:
        out.append(f'    ("libs/{lib}", include_str!("../../libs/{lib}")),')
    out.append("];")
    write(os.path.join(OUT_DIR, "embed_generated.rs"), out)


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    libs = read_libs()
    copy_libs(libs)
    generate_lib_list(libs)
    generate_embedded(libs)


if __name__ == "__main__":
    main()
