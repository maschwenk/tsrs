#!/usr/bin/env python3
# Transliterates the Go-generated Unicode casing tables in ts-ref/tsc/internal/stringutil to Rust.
# Identifier properties come from unicode-id-start, pinned to Go's Unicode version in Cargo.toml.
import re, sys, os

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
SRC = os.path.join(ROOT, 'ts-ref/tsc/internal/stringutil')
DST = os.path.join(ROOT, 'crates/tsrs_core/src/stringutil')

def snake_upper(name):
    s = re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', name)
    return s.upper()

def convert_tables(text):
    out = []
    for m in re.finditer(r'var (\w+) = &unicode\.RangeTable\{(.*?)\n\}', text, re.S):
        name, body = m.group(1), m.group(2)
        r16 = re.search(r'R16: \[\]unicode\.Range16\{(.*?)\n\t\}', body, re.S)
        r32 = re.search(r'R32: \[\]unicode\.Range32\{(.*?)\n\t\}', body, re.S)
        lo = re.search(r'LatinOffset: (\d+)', body)
        def ranges(block, kind):
            if not block:
                return ''
            items = re.findall(r'\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+), (\d+)\}', block.group(1))
            return ''.join(f'    {kind} {{ lo: {a}, hi: {b}, stride: {c} }},\n' for a, b, c in items)
        rn = snake_upper(name)
        out.append(f'static {rn}_R16: &[Range16] = &[\n{ranges(r16, "Range16")}];\n')
        out.append(f'static {rn}_R32: &[Range32] = &[\n{ranges(r32, "Range32")}];\n')
        out.append(f'pub(crate) static {rn}: RangeTable = RangeTable {{ r16: {rn}_R16, r32: {rn}_R32, latin_offset: {lo.group(1) if lo else 0} }};\n\n')
    return ''.join(out)

def go_str_to_rust(s):
    # Go "a" / "\U0001E93E" escapes -> Rust "\u{...}"
    s = re.sub(r'\\U([0-9A-Fa-f]{8})', lambda m: '\\u{%X}' % int(m.group(1), 16), s)
    s = re.sub(r'\\u([0-9A-Fa-f]{4})', lambda m: '\\u{%X}' % int(m.group(1), 16), s)
    return s

HEADER = '// Code generated by tools/gen/stringutil_tables.py from the Go sources. DO NOT EDIT.\n\n'

case = open(os.path.join(SRC, 'js_case_generated.go')).read()
entries = re.findall(r'\t(0x[0-9A-F]+):\s+\{lower: "([^"]*)", upper: "([^"]*)"(?:, conditionalLower: "([^"]*)")?, condition: specialCasingCondition(\w+)\}', case)
lines = []
prev = -1
for key, lower, upper, cond_lower, cond in entries:
    k = int(key, 16)
    assert k > prev, 'mappings must be sorted'
    prev = k
    lines.append(f'    ({key}, SpecialCasingMapping {{ lower: "{go_str_to_rust(lower)}", upper: "{go_str_to_rust(upper)}", conditional_lower: "{go_str_to_rust(cond_lower)}", condition: SpecialCasingCondition::{cond} }}),\n')
with open(os.path.join(DST, 'js_case_generated.rs'), 'w') as f:
    f.write(HEADER)
    f.write('use super::rangetable::{Range16, Range32, RangeTable};\n\n')
    f.write('#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub(crate) enum SpecialCasingCondition {\n    None,\n    FinalSigma,\n}\n\n')
    f.write('#[derive(Clone, Copy, Debug)]\npub(crate) struct SpecialCasingMapping {\n    pub lower: &\'static str,\n    pub upper: &\'static str,\n    pub conditional_lower: &\'static str,\n    pub condition: SpecialCasingCondition,\n}\n\n')
    f.write('// Sorted by code point; looked up with binary search (Go uses a map).\n')
    f.write(f'pub(crate) static SPECIAL_CASING_MAPPINGS: &[(i32, SpecialCasingMapping)] = &[\n{"".join(lines)}];\n\n')
    f.write(convert_tables(case))
print(len(entries), 'casing entries')
