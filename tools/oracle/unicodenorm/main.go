// Generates crates/tsrs_core/src/stringutil/norm_generated.rs: the Go `unicode.Mn` and `unicode.Upper` range tables
// and the golang.org/x/text/unicode/norm NFD data (full canonical decompositions and canonical combining classes)
// used by the language service's organize-imports collation (ls/lsutil/organizeimports.go).
//
// Build/run from the Go module: copy to ts-ref/tsc/cmd/tsrs-oracle-unicodenorm/main.go and
//   GOTOOLCHAIN=auto go run ./cmd/tsrs-oracle-unicodenorm > <repo>/crates/tsrs_core/src/stringutil/norm_generated.rs
package main

import (
	"fmt"
	"os"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"golang.org/x/text/unicode/norm"
)

func writeTable(w *strings.Builder, name string, t *unicode.RangeTable) {
	fmt.Fprintf(w, "static %s_R16: &[Range16] = &[\n", name)
	for _, r := range t.R16 {
		fmt.Fprintf(w, "    Range16 { lo: 0x%04x, hi: 0x%04x, stride: %d },\n", r.Lo, r.Hi, r.Stride)
	}
	fmt.Fprintf(w, "];\n")
	fmt.Fprintf(w, "static %s_R32: &[Range32] = &[\n", name)
	for _, r := range t.R32 {
		fmt.Fprintf(w, "    Range32 { lo: 0x%x, hi: 0x%x, stride: %d },\n", r.Lo, r.Hi, r.Stride)
	}
	fmt.Fprintf(w, "];\n")
	fmt.Fprintf(w, "pub(crate) static %s: RangeTable = RangeTable { r16: %s_R16, r32: %s_R32, latin_offset: %d };\n\n", name, name, name, t.LatinOffset)
}

func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		fmt.Fprintf(&b, "\\u{%x}", r)
	}
	b.WriteByte('"')
	return b.String()
}

func main() {
	var w strings.Builder
	w.WriteString("// Code generated by tools/oracle/unicodenorm (Go " + strconv.Quote(unicode.Version) + " tables, x/text norm " + norm.Version + "). DO NOT EDIT.\n\n")
	w.WriteString("use super::rangetable::{Range16, Range32, RangeTable};\n\n")
	writeTable(&w, "UNICODE_MN", unicode.Mn)
	writeTable(&w, "UNICODE_UPPER", unicode.Upper)

	w.WriteString("// Full canonical decomposition (norm.NFD of the single rune) of every rune whose NFD differs from itself,\n")
	w.WriteString("// except the algorithmically decomposed Hangul syllables U+AC00..U+D7A3. Sorted by code point.\n")
	w.WriteString("pub(crate) static NFD_DECOMPOSITIONS: &[(u32, &str)] = &[\n")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF || r >= 0xAC00 && r <= 0xD7A3 {
			continue
		}
		s := string(r)
		d := norm.NFD.String(s)
		if d != s {
			fmt.Fprintf(&w, "    (0x%x, %s),\n", r, rustString(d))
		}
	}
	w.WriteString("];\n\n")

	w.WriteString("// Canonical combining class of every rune with a non-zero class. Sorted by code point.\n")
	w.WriteString("pub(crate) static CANONICAL_COMBINING_CLASS: &[(u32, u8)] = &[\n")
	buf := make([]byte, 4)
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		n := utf8.EncodeRune(buf, r)
		if ccc := norm.NFD.Properties(buf[:n]).CCC(); ccc != 0 {
			fmt.Fprintf(&w, "    (0x%x, %d),\n", r, ccc)
		}
	}
	w.WriteString("];\n")
	os.Stdout.WriteString(w.String())
}
