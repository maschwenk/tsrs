#!/usr/bin/env python3
"""Writes the type registry of the lsproto oracle from Go's lsp_generated.go: registry_gen.go (Go) and
crates/tsrs_lsproto/tests/oracle_registry/mod.rs (Rust). Every structure, union, literal type and enumeration
of the protocol is registered (not the Resolved* capability views, which have no JSON codec)."""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
go = open(os.path.join(ROOT, "ts-ref/tsc/internal/lsp/lsproto/lsp_generated.go")).read()

names = []
for m in re.finditer(r"^type (\w+) (struct \{|struct\{\}|int32$|uint32$|string$)", go, re.M):
    name = m.group(1)
    if name.startswith("Resolved") or name == "RegisterOptions":
        continue
    names.append(name)
names += ["Message", "RequestMessage", "ResponseMessage"]

with open(os.path.join(HERE, "registry_gen.go"), "w") as f:
    f.write("// Code generated by gen_registry.py; DO NOT EDIT.\n\npackage main\n\n")
    f.write('import "github.com/microsoft/TypeScript/tsc/internal/lsp/lsproto"\n\n')
    f.write("var registryNames = []string{\n")
    for n in names:
        if n in ("Message", "RequestMessage", "ResponseMessage"):
            continue
        f.write(f'\t"{n}",\n')
    f.write("}\n\nvar registry = map[string]func() any{\n")
    for n in names:
        f.write(f'\t"{n}": func() any {{ return new(lsproto.{n}) }},\n')
    f.write("}\n")

os.makedirs(os.path.join(ROOT, "crates/tsrs_lsproto/tests/oracle_registry"), exist_ok=True)
with open(os.path.join(ROOT, "crates/tsrs_lsproto/tests/oracle_registry/mod.rs"), "w") as f:
    f.write("// Code generated by tools/oracle/lsproto/gen_registry.py; DO NOT EDIT.\n\n")
    f.write("use tsrs_lsproto::*;\n\n")
    f.write("pub fn roundtrip(name: &str, data: &[u8]) -> Option<String> {\n")
    f.write("    Some(match name {\n")
    for n in names:
        f.write(f'        "{n}" => run::<{n}>(data),\n')
    f.write("        _ => return None,\n    })\n}\n\n")
    f.write("fn run<T: Json>(data: &[u8]) -> String {\n")
    f.write("    match unmarshal::<T>(data) {\n")
    f.write("        Ok(v) => match marshal(&v) {\n")
    f.write("            Ok(s) => format!(\"OK {s}\"),\n")
    f.write("            Err(e) => format!(\"MERR {e}\"),\n")
    f.write("        },\n")
    f.write("        Err(e) => format!(\"ERR {}\", e.to_string().replace('\\n', \"\\\\n\")),\n")
    f.write("    }\n}\n")
print(len(names), "types")
