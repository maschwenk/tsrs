import unittest
from unittest.mock import patch
import xml.etree.ElementTree as ET

import chart
import history
import publish
import run


class ReportingTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.historical = json.loads((Path(__file__).parent / 'results/2026-10-08-6e82c526ff8e.json').read_text())

    def resized(self):
        result = copy.deepcopy(self.historical)
        result['modes'] = ['checkers16' if mode == 'checkers64' else mode for mode in result['modes']]
        result['mode_reps']['checkers16'] = result['mode_reps'].pop('checkers64')
        for project in result['projects'].values():
            project['checkers16'] = project.pop('checkers64')
            for mode in ('wide', 'checkers16'):
                machine = project[mode]['machine']
                machine.update(cpus=16, memory_gb=63, label='Depot CI 16 vCPU')
        return result

    def test_legacy_table_update_preserves_published_chart(self):
        contents = ('# Project\n\n![Benchmark](bench/large-projects.svg)\n',
                    '<!-- bench:start -->\n<!-- Generated by bench/publish.py -->\nCurrent\n<!-- bench:end -->\n')
        with tempfile.TemporaryDirectory() as directory:
            readme = Path(directory) / 'README.md'
            for content in contents:
                with self.subTest(content=content):
                    readme.write_text(content)
                    run.update_readme(readme, run.markdown(self.historical, ['wide']))
                    self.assertEqual(content, readme.read_text())

    def test_historical_and_new_results_name_their_own_hardware(self):
        old = run.markdown(self.historical, ['wide', 'checkers64'])
        new = run.markdown(self.resized(), ['wide', 'checkers16'])
        self.assertIn('Default settings on 64 vCPUs', old)
        self.assertIn('`--checkers 64`', old)
        self.assertIn('Default settings on 16 vCPUs', new)
        self.assertIn('bun check gets `--threads 16`', new)
        self.assertNotIn('64-vCPU', new)

    def test_merge_keeps_fixed_and_wide_machine_provenance(self):
        resized = self.resized()
        partials = []
        for modes in (['default', 'single', 'checkers8'], ['wide', 'checkers16']):
            part = copy.deepcopy(resized)
            part['modes'] = modes
            part['projects'] = {'vscode': {mode: copy.deepcopy(resized['projects']['vscode'][mode]) for mode in modes}}
            if 'wide' in modes:
                part['machine'] = part['projects']['vscode']['wide']['machine']
            for cell in part['projects']['vscode'].values():
                cell.pop('machine', None)
            part['raw'] = []
            partials.append(part)
        with tempfile.TemporaryDirectory() as directory:
            paths = [Path(directory) / f'{i}.json' for i in range(2)]
            for path, part in zip(paths, partials):
                path.write_text(json.dumps(part))
            merged = run.merge_results({'projects': [{'name': 'vscode'}]}, paths)
        self.assertEqual(8, merged['machine']['cpus'])
        self.assertEqual(16, merged['projects']['vscode']['wide']['machine']['cpus'])
        self.assertIn('Default settings on 16 vCPUs', run.markdown(merged, ['wide']))

    def test_merge_adds_the_watch_table_to_reports_but_not_the_chart(self):
        stats = lambda scale: {'runs': 3, 'ok_runs': 3, 'initial_s': 9.0 * scale, 'first_edit_s': 2.0 * scale,
                               'repeat_edit_s': 1.9 * scale, 'type_error_s': 1.9 * scale, 'errors': 359,
                               'peak_rss_bytes': 12 * 2**30 * scale, 'final_rss_bytes': 11 * 2**30 * scale}
        watch = {'kind': 'watch', 'date': self.historical['date'], 'machine': self.historical['machine'],
                 'tsrs': self.historical['tsrs'], 'tsgo': self.historical['tsgo'], 'duration_s': 60,
                 'watch': {'project': 'vscode', 'project_path': 'src', 'leaf': 'src/leaf.test.ts', 'reps': 5,
                           'tsgo_reps': 3, 'edits': 5, 'machine': self.historical['machine'],
                           'tsgo': stats(1), 'tsrs': stats(0.25), 'sessions': {}}}
        with tempfile.TemporaryDirectory() as directory:
            paths = [Path(directory) / 'all.json', Path(directory) / 'watch.json']
            paths[0].write_text(json.dumps(self.historical))
            paths[1].write_text(json.dumps(watch))
            merged = run.merge_results({'projects': [{'name': name} for name in self.historical['projects']]}, paths)
            other = dict(watch, tsrs=dict(watch['tsrs'], commit='0' * 40))
            paths[1].write_text(json.dumps(other))
            with self.assertRaises(SystemExit):
                run.merge_results({'projects': [{'name': 'vscode'}]}, paths)
        self.assertEqual(watch['watch'], merged['watch'])
        summary = run.markdown(merged, ['wide'])
        self.assertIn('### Watch mode (vscode)', summary)
        self.assertIn('| repeat comment edit | 1.90 s | 475 ms | 4.00x faster |', summary)
        self.assertIn('| peak RSS | 12.00 GiB | 3.00 GiB | 4.00x less |', summary)
        self.assertNotIn('Watch mode', run.markdown(self.historical, ['wide']))
        self.assertEqual(chart.svg({k: v for k, v in merged.items() if k != 'watch'}), chart.svg(merged))

    def test_history_starts_new_baseline_only_for_changed_hardware(self):
        new = self.resized()
        old_wall = self.historical['projects']['vscode']['wide']['tsrs']['wall_s']
        new['projects']['vscode']['wide']['tsrs']['wall_s'] = old_wall * 2
        later = copy.deepcopy(new)
        later['projects']['vscode']['wide']['tsrs']['wall_s'] *= 1.1
        rendered = history.table([self.historical, new, later], ['vscode'], 'wide_wall', True).splitlines()
        self.assertIn('(new baseline)', rendered[2])
        self.assertNotIn('+100.0%', rendered[2])
        self.assertIn('+10.0%', rendered[3])
        fixed = history.table([self.historical, new], ['vscode'], 'wall', True)
        self.assertNotIn('new baseline', fixed)


class PublishTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.historical = json.loads((Path(__file__).parent / 'results/2026-10-11-177e6cf55d52.json').read_text())
        cls.historical['projects'] = {'vscode': cls.historical['projects']['vscode']}

    def setUp(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.repo = Path(directory.name)
        self.git('init', '--quiet')
        self.commits = []
        for index in range(3):
            self.git('commit', '--quiet', '--allow-empty', '-m', f'Commit {index}')
            self.commits.append(self.git('rev-parse', 'HEAD'))
        self.out_dir = self.repo / 'bench/results'
        self.out_dir.mkdir(parents=True)
        self.report = self.repo / 'bench/RESULTS.md'
        self.report.write_text('# Benchmark results\n\n<!-- bench:start -->\n<!-- bench:end -->\n')
        self.image = self.repo / 'bench/large-projects.svg'
        repo_patch = patch.object(publish, 'REPO', self.repo)
        repo_patch.start()
        self.addCleanup(repo_patch.stop)

    def git(self, *args):
        return subprocess.check_output([
            'git', '-c', 'user.name=Benchmark checks', '-c', 'user.email=bench@example.invalid',
            '-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=/dev/null', *args,
        ], cwd=self.repo, text=True).strip()

    def result(self, commit):
        result = copy.deepcopy(self.historical)
        result['tsrs']['commit'] = commit
        return result

    def publish(self, result):
        path = self.out_dir / f"2026-10-11-{result['tsrs']['commit'][:12]}.json"
        path.write_text(json.dumps(result))
        path.with_suffix('.md').write_text('Full benchmark report\n')
        return publish.publish(path, self.report, self.image)

    def latest(self):
        return self.report.read_bytes(), self.image.read_bytes()

    def test_publishes_wide_summary_chart_and_source_links(self):
        commit = self.commits[0]
        self.assertTrue(self.publish(self.result(commit)))
        report, svg = self.latest()
        report = report.decode()
        self.assertIn(f'tsrs commit: `{commit[:12]}`', report)
        self.assertIn('### Default settings on 16 vCPUs', report)
        self.assertNotIn('### `--singleThreaded`', report)
        self.assertNotIn('### `--checkers', report)
        self.assertNotIn('### Scaling', report)
        self.assertTrue(report.startswith('# Benchmark results\n\n<!-- bench:start -->\n'))
        self.assertIn('Method: [benchmark methodology](https://github.com/maschwenk/tsrs/blob/main/bench/README.md)', report)
        self.assertIn(f'](results/2026-10-11-{commit[:12]}.json)', report)
        self.assertIn(f'](results/2026-10-11-{commit[:12]}.md)', report)
        self.assertEqual('{http://www.w3.org/2000/svg}svg', ET.fromstring(svg).tag)

    def test_publishing_preserves_handwritten_sections_around_tables(self):
        before = '# Benchmark results\n\nPinned projects and methodology.\n\n'
        after = '\n\n## Historical comparison\n\nThese measurements are a separate snapshot.\n'
        self.report.write_text(before + '<!-- bench:start -->\nOld tables.\n<!-- bench:end -->' + after)
        for commit in self.commits[:2]:
            self.assertTrue(self.publish(self.result(commit)))
            report = self.report.read_text()
            self.assertTrue(report.startswith(before + '<!-- bench:start -->\n'))
            self.assertTrue(report.endswith('<!-- bench:end -->' + after))
            self.assertEqual(1, report.count('<!-- bench:start -->'))
            self.assertEqual(1, report.count('Generated by bench/publish.py'))
            self.assertNotIn('Old tables.', report)

    def test_out_of_order_results_preserve_newest_report_and_chart(self):
        self.assertTrue(self.publish(self.result(self.commits[0])))
        self.assertTrue(self.publish(self.result(self.commits[2])))
        latest = self.latest()
        self.assertFalse(self.publish(self.result(self.commits[1])))
        self.assertEqual(latest, self.latest())

    def test_rerunning_same_commit_updates_report_and_chart(self):
        result = self.result(self.commits[1])
        self.assertTrue(self.publish(result))
        old_report, old_svg = self.latest()
        result['date'] = '2026-10-11 12:00 UTC'
        result['projects']['vscode']['wide']['tsrs']['wall_s'] *= 2
        self.assertTrue(self.publish(result))
        report, svg = self.latest()
        self.assertNotEqual(old_report, report)
        self.assertNotEqual(old_svg, svg)
        self.assertIn(result['date'].encode(), report)

    def test_results_without_wide_measurements_preserve_latest(self):
        self.assertTrue(self.publish(self.result(self.commits[0])))
        latest = self.latest()
        for missing in ('mode', 'cells'):
            with self.subTest(missing=missing):
                result = self.result(self.commits[2])
                if missing == 'mode':
                    result['modes'].remove('wide')
                else:
                    del result['projects']['vscode']['wide']
                self.assertFalse(self.publish(result))
                self.assertEqual(latest, self.latest())


if __name__ == '__main__':
    unittest.main()
