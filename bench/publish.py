#!/usr/bin/env python3
"""Render the latest benchmark report and README chart during the results commit step.

    python3 bench/publish.py bench/results/<date>-<commit>.json

Older backfills and runs without wide results keep the existing report and chart.
"""

import argparse
import json
from pathlib import Path
import re
import subprocess

import chart
import run

REPO = run.REPO


def publish(result_path: Path, report: Path, image_path: Path) -> bool:
    result = json.loads(result_path.read_text())
    if "wide" not in result["modes"] or not any("wide" in p for p in result["projects"].values()):
        print("No wide results; keeping the latest report and chart.")
        return False

    measured = subprocess.check_output(
        ["git", "rev-parse", "--verify", f"{result['tsrs']['commit']}^{{commit}}"], cwd=REPO, text=True).strip()
    report_text = report.read_text() if report.exists() else "# Benchmark results\n\n"
    # On the first publish after moving the tables, README still identifies the displayed result.
    previous = report if report.exists() else REPO / "README.md"
    match = re.search(r"tsrs commit: `([0-9a-f]{7,40})`", previous.read_text()) if previous.exists() else None
    if match:
        resolved = subprocess.run(["git", "rev-parse", "--verify", f"{match[1]}^{{commit}}"],
                                  cwd=REPO, capture_output=True, text=True)
        displayed = resolved.stdout.strip()
        if resolved.returncode == 0 and displayed != measured and subprocess.run(
                ["git", "merge-base", "--is-ancestor", measured, displayed], cwd=REPO).returncode == 0:
            print(f"Keeping the report and chart of {displayed[:12]}, a descendant of {measured[:12]}.")
            return False

    # Render both before writing either so a rendering failure cannot leave a mismatched pair.
    svg = chart.svg(result)
    table = run.markdown(result, ["wide"]).replace(
        "[`bench/README.md`](bench/README.md)", "[benchmark method](README.md)")
    notice = "<!-- Generated by bench/publish.py; edit the generator, not this section. -->\n\n"
    sources = f"\n[All modes](results/{result_path.stem}.md) · [Raw measurements](results/{result_path.name})\n"
    block = f"{run.START}\n{notice}{table}{sources}{run.END}"
    if run.START in report_text and run.END in report_text:
        before, rest = report_text.split(run.START, 1)
        _, after = rest.split(run.END, 1)
        report_text = before + block + after
    else:
        report_text += ("\n" if report_text and not report_text.endswith("\n") else "") + block + "\n"
    report.parent.mkdir(parents=True, exist_ok=True)
    image_path.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(report_text)
    image_path.write_text(svg)
    print(f"Updated {report} and {image_path} for {measured[:12]}.")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("result", type=Path)
    args = parser.parse_args()
    publish(args.result, run.BENCH / "RESULTS.md", run.BENCH / "results/latest.svg")


if __name__ == "__main__":
    main()
