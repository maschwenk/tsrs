#!/usr/bin/env python3
"""Import the pinned Go rule tests without running or depending on the Go linter.

Usage: python3 crates/tsrs_linter/tests/import_tsgolint.py /path/to/tsgolint
Only regeneration needs Go; cargo test consumes the checked-in data.
"""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

REVISION = "24b18b48c47b7ae0d84e21a0e974575026e27908"
ROOT = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("checkout", type=Path, help="tsgolint checkout at the pinned revision")
UPSTREAM = parser.parse_args().checkout.resolve()
revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=UPSTREAM, text=True).strip()
if revision != REVISION:
    raise SystemExit(f"expected tsgolint {REVISION}, got {revision}")
imported_paths = [
    "internal/rules/no_floating_promises/no_floating_promises_test.go",
    "internal/rule_tester/__snapshots__/no-floating-promises.snap",
    "internal/rules/fixtures",
    "LICENSE",
]
dirty = subprocess.check_output(
    ["git", "status", "--porcelain", "--", *imported_paths], cwd=UPSTREAM, text=True
)
if dirty:
    raise SystemExit(f"imported upstream files must match the pinned revision:\n{dirty}")

# Evaluate the original Go table constructors, including t.Run loops and computed
# suggestion outputs. The replacement tester records inputs instead of linting.
source = (UPSTREAM / "internal/rules/no_floating_promises/no_floating_promises_test.go").read_text()
tests = re.findall(r"^func (Test\w+)\(t \*testing.T\)", source, re.M)
source = source.replace("package no_floating_promises", "package main", 1)
source = re.sub(r"import \([\s\S]*?\n\)", 'import "strings"', source, count=1)
source = source.replace("testing.T", "T").replace("rule_tester.", "")
source = source.replace("fixtures.GetRootDir()", '"/fixtures"')
stub = r'''
package main
import ("encoding/json"; "fmt"; "os"; "strings")
type T struct { name string }
func (t *T) Parallel() {}
func (t *T) Run(name string, run func(*T)) { run(&T{t.name+"/"+strings.ReplaceAll(name," ","_")}) }
type ValidTestCase struct {
    Code string; Only bool; Skip bool; FileName string; Options any; TSConfig string; Tsx bool; Files map[string]string
}
type InvalidTestCaseSuggestion struct { MessageId string; Output string }
type InvalidTestCaseError struct {
    MessageId string; Line int; Column int; EndLine int; EndColumn int; Suggestions []InvalidTestCaseSuggestion
}
type InvalidTestCase struct {
    Code string; Only bool; Skip bool; FileName string; Output []string; Errors []InvalidTestCaseError
    TSConfig string; Options any; Tsx bool; Files map[string]string
}
type NoFloatingPromisesOptions = json.RawMessage
var NoFloatingPromisesRule struct{}
func OptionsFromJSON[T any](text string) T { var v T; if err:=json.Unmarshal([]byte(text),&v);err!=nil{panic(err)};return v }
type Case struct { Name string; Valid bool; Config string; Data any }
var cases []Case
func RunRuleTester(_ string, config string, t *T, _ *struct{}, valid []ValidTestCase, invalid []InvalidTestCase) {
    for i,c:=range valid { if c.Only {panic("focused upstream case")}; cases=append(cases,Case{fmt.Sprintf("%s/valid-%d",t.name,i),true,config,c}) }
    for i,c:=range invalid { if c.Only {panic("focused upstream case")}; cases=append(cases,Case{fmt.Sprintf("%s/invalid-%d",t.name,i),false,config,c}) }
}
'''
stub += "\nfunc main() {\n" + "\n".join(f'{name}(&T{{"{name}"}})' for name in tests)
stub += "\nif err:=json.NewEncoder(os.Stdout).Encode(cases);err!=nil{panic(err)}\n}\n"
with tempfile.TemporaryDirectory(prefix="tsrs-import-linter-") as temp:
    temp = Path(temp)
    (temp / "cases.go").write_text(source)
    (temp / "main.go").write_text(stub)
    env = {**os.environ, "GOWORK": "off", "GOTOOLCHAIN": "local"}
    env.setdefault("GOCACHE", str(temp / "cache"))
    cases = json.loads(subprocess.check_output(["go", "run", "main.go", "cases.go"], cwd=temp, env=env))

snapshots = (UPSTREAM / "internal/rule_tester/__snapshots__/no-floating-promises.snap").read_text()
keys = set(re.findall(r"^\[(.*) - 1\]$", snapshots, re.M))
expected_keys = {c["Name"] for c in cases if not c["Valid"]}
if keys != expected_keys:
    raise SystemExit(f"snapshot/case mismatch: {keys ^ expected_keys}")
fixtures = UPSTREAM / "internal/rules/fixtures"
files = {p.relative_to(fixtures).as_posix(): p.read_text() for p in sorted(fixtures.rglob("*")) if p.is_file() and p.suffix != ".go"}
output = ROOT / "fixtures/tsgolint"
output.mkdir(parents=True, exist_ok=True)
(output / "no_floating_promises.json").write_text(json.dumps({"revision": REVISION, "files": files, "cases": cases}, indent=2, ensure_ascii=False) + "\n")
(output / "no-floating-promises.snap").write_text(snapshots)
(output / "LICENSE").write_text((UPSTREAM / "LICENSE").read_text())

rust = '''// Code generated by tests/import_tsgolint.py; DO NOT EDIT.
// Upstream tests are MIT licensed; see fixtures/tsgolint/LICENSE.
mod rule_tester;

use std::sync::OnceLock;
use rule_tester::Suite;

fn suite() -> &'static Suite {
    static SUITE: OnceLock<Suite> = OnceLock::new();
    SUITE.get_or_init(|| serde_json::from_str(include_str!("fixtures/tsgolint/no_floating_promises.json")).unwrap())
}

macro_rules! case {
    ($(#[$attribute:meta])* $name:ident, $index:expr, $upstream:literal) => {
        $(#[$attribute])*
        #[test]
        fn $name() {
            let case = &suite().cases[$index];
            assert_eq!(case.name, $upstream);
            rule_tester::run_case(suite(), case, &tsrs_linter::NO_FLOATING_PROMISES,
                include_str!("fixtures/tsgolint/no-floating-promises.snap"));
        }
    };
}

'''
for i, case in enumerate(cases):
    name = re.sub(r"[^a-zA-Z0-9_]", "_", case["Name"])
    name = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
    ignored = '#[ignore = "Skipped upstream (Skip: true)"] ' if case["Data"]["Skip"] else ""
    rust += f'case!({ignored}{name}, {i}, {json.dumps(case["Name"])});\n'
rust += f'''
#[test]
fn all_upstream_cases_are_registered() {{
    assert_eq!(suite().revision, "{REVISION}");
    assert_eq!(suite().cases.len(), {len(cases)});
}}
'''
(ROOT / "no_floating_promises.rs").write_text(rust)
subprocess.run(["rustfmt", "--edition", "2024", str(ROOT / "no_floating_promises.rs"), "--config", "skip_children=true"], check=True)
print(f"Imported {len(cases)} cases ({sum(c['Valid'] for c in cases)} valid, {len(expected_keys)} invalid) and {len(keys)} snapshots from {REVISION}")
